export function t(lang, path) {
  const keys = path.split('.');
  let val = LABELS[lang];
  for (const k of keys) {
    if (val && typeof val === 'object') val = val[k];
    else return path;
  }
  return val;
}

export function formatTemplate(str, vars) {
  if (!str) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars && vars[k] !== undefined ? vars[k] : `{${k}}`));
}
